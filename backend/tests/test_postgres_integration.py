"""Tests that only PostgreSQL can answer.

They skip when no PostgreSQL is reachable, so the suite stays runnable
anywhere. What they cover cannot be simulated on SQLite:

* the Alembic migration actually produces the schema the models describe;
* PostgreSQL rejects NUL bytes in text, which a real corrupted transcript on
  this machine contains.
"""

from __future__ import annotations

import uuid

import pytest
from sqlalchemy import create_engine, func, select, text
from sqlalchemy.exc import OperationalError
from sqlalchemy.orm import sessionmaker

from app.config import get_settings
from app.db.base import Base
from app.models.entities import Message
from app.models.entities import Session as SessionRow
from app.repositories.session_repository import SessionRepository
from app.services.aggregator import SessionAggregator

from .conftest import FIXED_NOW
from .test_discovery_and_aggregator import NullCcusage


@pytest.fixture(scope="module")
def pg_url() -> str:
    url = get_settings().database_url
    if not url.startswith("postgresql"):
        pytest.skip("DATABASE_URL does not point at PostgreSQL")
    try:
        engine = create_engine(url)
        with engine.connect() as connection:
            connection.execute(text("SELECT 1"))
        engine.dispose()
    except OperationalError:
        pytest.skip("PostgreSQL is not reachable")
    return url


@pytest.fixture
def pg_session(pg_url: str):
    """An isolated schema per test, dropped afterwards."""
    schema = f"test_{uuid.uuid4().hex[:12]}"
    engine = create_engine(pg_url, future=True)
    with engine.begin() as connection:
        connection.execute(text(f'CREATE SCHEMA "{schema}"'))
    scoped = engine.execution_options(schema_translate_map={None: schema})
    Base.metadata.create_all(scoped)
    session = sessionmaker(bind=scoped, expire_on_commit=False)()
    try:
        yield session
    finally:
        session.close()
        with engine.begin() as connection:
            connection.execute(text(f'DROP SCHEMA "{schema}" CASCADE'))
        engine.dispose()


def test_migration_matches_the_models(pg_url: str):
    """``alembic check`` fails if the models drifted from the migrations."""
    from alembic import command
    from alembic.config import Config
    from alembic.util.exc import AutogenerateDiffsDetected
    from pathlib import Path

    backend = Path(__file__).resolve().parents[1]
    config = Config(str(backend / "alembic.ini"))
    config.set_main_option("script_location", str(backend / "alembic"))
    try:
        command.check(config)
    except AutogenerateDiffsDetected as exc:
        pytest.fail(f"models and migrations have drifted: {exc}")


def test_nul_bytes_would_be_rejected_by_postgres(pg_session):
    """Documents the constraint the scrubber exists for."""
    from sqlalchemy.exc import DBAPIError

    pg_session.add(
        SessionRow(claude_session_id="nul-probe", status="completed")
    )
    pg_session.flush()
    row = pg_session.scalar(select(SessionRow))
    pg_session.add(
        Message(
            session_id=row.id,
            sequence=1,
            role="user",
            message_type="human_prompt",
            content="antes\x00depois",
        )
    )
    with pytest.raises(DBAPIError):
        pg_session.flush()
    pg_session.rollback()


def test_a_transcript_with_nul_bytes_persists_after_scrubbing(pg_session, transcript):
    report = SessionAggregator(NullCcusage(), enable_git=False).build(
        transcript("session-basic"), now=FIXED_NOW
    )
    report.messages[0].content = "antes\x00depois"
    SessionRepository(pg_session).save(report)
    pg_session.commit()

    row = pg_session.scalar(select(SessionRow))
    assert any("NUL byte" in w for w in row.collection_warnings)
    assert pg_session.scalar(select(func.count(Message.id))) == len(report.messages)


def test_jsonb_round_trips_nested_structures(pg_session, transcript):
    report = SessionAggregator(NullCcusage(), enable_git=False).build(
        transcript("session-basic"), now=FIXED_NOW
    )
    SessionRepository(pg_session).save(report)
    pg_session.commit()
    row = pg_session.scalar(select(SessionRow))
    assert row.models_used == [
        "claude-haiku-4-5-20251001",
        "claude-opus-5",
    ]
